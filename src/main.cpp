// -------- STATES --------
enum State {
  HOME, // Default screen
  DISPENSE_8, // 8 oz dispense
  DISPENSE_16, // 16 oz dispense
  DISPENSE_32, // 32 oz dispense
  ALREADY // Already dispensing
};

State currentState = HOME; // initialize current state to HOME
State activeDispense = HOME; // initialize active dispense state to HOME 
unsigned long stateStartTime = 0; // For timing how long we've been in a state
const unsigned long dispenseTime = 10000; // Dispense time of 10 seconds

void loop() {
// -------- INPUTS --------
  int b1 = digitalRead(btn1); // 8 oz
  int b2 = digitalRead(btn2); // 16 oz
  int b3 = digitalRead(btn3); // 32 oz

  unsigned long now = millis();

// -------- DEBOUNCE + EDGE DETECTION --------
  bool press1 = false;
  bool press2 = false;
  bool press3 = false;

  if ((now - lastDebounceTime) > debounceDelay) {
    if (b1 && !lastB1) press1 = true;
    if (b2 && !lastB2) press2 = true;
    if (b3 && !lastB3) press3 = true;

    lastDebounceTime = now;
  }

  lastB1 = b1;
  lastB2 = b2;
  lastB3 = b3;

// -------- STATE LOGIC --------
	switch (currentState) {

	case HOME:
		if (press1) {
		currentState = DISPENSE_8;
		stateStartTime = now;  
		}
		else if (press2) {
		currentState = DISPENSE_16;
		stateStartTime = now;
		}
		else if (press3) {
		currentState = DISPENSE_32;
		stateStartTime = now;
		}
		break;

	case DISPENSE_8:
		if (press1) {
		currentState = ALREADY;
		}
		else if (now - stateStartTime >= dispenseTime) {
		currentState = HOME;
		}
		break;

	case DISPENSE_16:
		if (press2) {
		currentState = ALREADY;
		}
		else if (now - stateStartTime >= dispenseTime) {
		currentState = HOME;
		}
		break;

	case DISPENSE_32:
		if (press3) {
		currentState = ALREADY;
		}
		else if (now - stateStartTime >= dispenseTime) {
		currentState = HOME;
		}
		break;

	case ALREADY:
		if (now - stateStartTime >= dispenseTime) {
		currentState = HOME;
		}
		break;
	}

// -------- OUTPUT LOGIC --------

	// Check if we are dispensing anything
	bool dispensing =(currentState == DISPENSE_8 || currentState == DISPENSE_16 || currentState == DISPENSE_32);

	// Run BOTH motors forward (CORRECTED FOR YOUR WIRING)
	if (dispensing) {
		// Motor A (reversed wiring)
		digitalWrite(out1, LOW);   // IN1
		digitalWrite(out2, HIGH);  // IN2

		// Motor B (normal wiring)
		digitalWrite(out3, HIGH);  // IN3
		digitalWrite(out4, LOW);   // IN4
	}
	else {
		// Stop everything
		digitalWrite(out1, LOW);
		digitalWrite(out2, LOW);
		digitalWrite(out3, LOW);
		digitalWrite(out4, LOW);
	}

  // -------- DISPLAY --------
  u8g2.clearBuffer();

	switch (currentState) {
		case HOME:
			u8g2.drawXBMP(0, 0, 128, 64, bitmap_Home);
			break;

		case DISPENSE_8:
			u8g2.drawXBMP(0, 0, 128, 64, bitmap_Dispense8fl);
			break;

		case DISPENSE_16:
			u8g2.drawXBMP(0, 0, 128, 64, bitmap_Dispense16fl);
			break;

		case DISPENSE_32:
			u8g2.drawXBMP(0, 0, 128, 64, bitmap_Dispense32fl);
			break;

		case ALREADY:
			u8g2.drawXBMP(0, 0, 128, 64, bitmap_AlreadyDispensing);
			break;
	}

  u8g2.sendBuffer();

  delay(20);
}