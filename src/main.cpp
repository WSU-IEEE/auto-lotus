  pinMode(btn1, INPUT_PULLDOWN); // 8 oz button
  pinMode(btn2, INPUT_PULLDOWN); // 16 oz button
  pinMode(btn3, INPUT_PULLDOWN); // 32 oz button

  // Outputs to control the L298N motor driver (assuming IN1, IN2 for motor 1 and IN3, IN4 for motor 2)
  pinMode(out1, OUTPUT); // Motor 1 Control IN1
  pinMode(out2, OUTPUT); // Motor 1 Control IN2 
  pinMode(out3, OUTPUT); // Motor 2 Control IN3
  pinMode(out4, OUTPUT); // Motor 2 Control IN4
